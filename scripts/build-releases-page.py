#!/usr/bin/env python3
"""Generate the site's /releases/ pages from CHANGELOG.md.

One page per released version under ``docs/releases/<version>/`` plus an index at
``docs/releases/``. The changelog is the only source: nothing is invented, releases
keep their order (newest first), and ``Unreleased`` is never published — it is work
that has not shipped and its notes change without a version bump.

Each page uses the site's ``prose`` layout and carries an explicit anchor per
``### Added`` / ``### Changed`` / ``### Fixed`` block so a CI log or PR comment can
link one block (``/releases/1.0.10/#added``).

Usage:
    python3 scripts/build-releases-page.py [docs-dir] [--check]

``--check`` renders into a temporary directory and fails when the committed pages
differ, so a stale release page cannot ship (the same contract as check-rule-docs.sh).
"""

from __future__ import annotations

import argparse
import re
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CHANGELOG = ROOT / "CHANGELOG.md"
REPOSITORY = "RohithV16/aem-code-analyser"
SITE = "https://rohithv16.github.io/aem-code-analyser"

HEADING = re.compile(r"^## \[([^\]]+)\](?:\s*[—–-]\s*(\d{4}-\d{2}-\d{2}))?\s*$")
SUBSECTION = re.compile(r"^### (.+?)\s*$")
FENCE = re.compile(r"^\s*```")


def slug(text: str) -> str:
    value = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    return value or "section"


def parse_changelog(text: str) -> list[dict]:
    releases: list[dict] = []
    current: dict | None = None
    section: dict | None = None
    in_fence = False

    for line in text.splitlines():
        if FENCE.match(line):
            in_fence = not in_fence
        if not in_fence:
            heading = HEADING.match(line)
            if heading:
                current = {
                    "version": heading.group(1).strip(),
                    "date": heading.group(2),
                    "sections": [],
                }
                releases.append(current)
                section = None
                continue
            subsection = SUBSECTION.match(line)
            if subsection and current is not None:
                section = {"title": subsection.group(1).strip(), "lines": []}
                current["sections"].append(section)
                continue
        if section is not None:
            section["lines"].append(line)

    for release in releases:
        for block in release["sections"]:
            while block["lines"] and not block["lines"][0].strip():
                block["lines"].pop(0)
            while block["lines"] and not block["lines"][-1].strip():
                block["lines"].pop()
    return releases


def published(releases: list[dict]) -> list[dict]:
    return [r for r in releases if r["version"].lower() != "unreleased"]


def unique_anchors(release: dict) -> list[str]:
    """Anchor per block, deterministic and unique even when Added appears twice."""
    seen: dict[str, int] = {}
    anchors = []
    for block in release["sections"]:
        base = slug(block["title"])
        seen[base] = seen.get(base, 0) + 1
        anchors.append(base if seen[base] == 1 else f"{base}-{seen[base]}")
    return anchors


def contents_summary(release: dict) -> str:
    counts: dict[str, int] = {}
    for block in release["sections"]:
        counts[block["title"]] = counts.get(block["title"], 0) + 1
    parts = []
    for title, count in counts.items():
        parts.append(f"{title} ({count})" if count > 1 else title)
    return " · ".join(parts) if parts else "No notes"


def render_version(release: dict, anchors: list[str]) -> str:
    version = release["version"]
    date = release["date"]
    released = f"Released {date}" if date else "Release date not recorded"
    lines = [
        "---",
        "layout: prose",
        f'title: "{version} — AEM Code Analyser release notes"',
        (
            "description: \"Release notes for AEM Code Analyser "
            f"{version}: rules added, behaviour changes and fixes, and which of them can "
            'fail a gate that passed on the previous version."'
        ),
        "nav: releases",
        f'release_version: "{version}"',
    ]
    if date:
        lines.append(f'release_date: "{date}"')
    lines += [
        "---",
        "",
        "<!-- Generated by scripts/build-releases-page.py from CHANGELOG.md — do not edit. -->",
        "",
        f"# AEM Code Analyser {version}",
        "",
        (
            f'<p class="muted">{released} · <a href="../">All release notes</a> · '
            f'<a href="https://github.com/{REPOSITORY}/releases/tag/v{version}" rel="noopener">'
            "GitHub release</a></p>"
        ),
        "",
        "> **Upgrading?** A rule added in a release can fail a gate that passed on the previous",
        "> version. Run this version once on a branch (`aem-analyser . --no-html`) before bumping CI,",
        "> and accept existing findings with `--update-baseline` when the change is deliberate.",
        "",
    ]
    for block, anchor in zip(release["sections"], anchors):
        lines += [f"## {block['title']}", f"{{: #{anchor}}}", ""]
        lines += block["lines"]
        lines.append("")
    if not release["sections"]:
        lines += ["_This release has no changes recorded in CHANGELOG.md._", ""]
    return "\n".join(lines)


def render_index(releases: list[dict]) -> str:
    lines = [
        "---",
        "layout: prose",
        'title: "Release notes"',
        (
            'description: "Every AEM Code Analyser release, newest first: the rules added, '
            'behaviour changes and fixes in each version, and which upgrades can fail a gate."'
        ),
        "nav: releases",
        "---",
        "",
        "<!-- Generated by scripts/build-releases-page.py from CHANGELOG.md — do not edit. -->",
        "",
        "# Release notes",
        "",
        (
            "Every released version, newest first. The **Added** sections are the ones to read "
            "before an upgrade: a new ERROR-severity rule fails a build that passed on the "
            "previous version. Each version page is generated from "
            f"[CHANGELOG.md](https://github.com/{REPOSITORY}/blob/main/CHANGELOG.md), which is "
            "the single source for these notes."
        ),
        "",
        "| Version | Released | Contents |",
        "|---|---|---|",
    ]
    for release in releases:
        version = release["version"]
        date = release["date"] or "—"
        lines.append(
            f"| **[{version}]({version}/)** | {date} | {contents_summary(release)} |"
        )
    lines += [
        "",
        "Prefer to verify a download before running it? The "
        "[installer](https://github.com/RohithV16/aem-code-analyser/blob/main/install.sh) checks "
        "the jar against the release's `SHA256SUMS.txt`.",
        "",
    ]
    return "\n".join(lines)


def expected_pages(releases: list[dict]) -> dict[str, str]:
    pages = {"index.md": render_index(releases)}
    for release in releases:
        pages[f"{release['version']}/index.md"] = render_version(
            release, unique_anchors(release)
        )
    return pages


def write_pages(target: Path, pages: dict[str, str]) -> None:
    if target.exists():
        shutil.rmtree(target)
    for name, content in pages.items():
        path = target / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")


def diff_pages(target: Path, pages: dict[str, str]) -> list[str]:
    problems = []
    committed = {
        str(path.relative_to(target)): path.read_text(encoding="utf-8")
        for path in target.rglob("*.md")
    } if target.exists() else {}
    for name, content in pages.items():
        if name not in committed:
            problems.append(f"missing: releases/{name}")
        elif committed[name] != content:
            problems.append(f"stale:   releases/{name}")
    for name in sorted(set(committed) - set(pages)):
        problems.append(f"extra:   releases/{name}")
    return problems


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate docs/releases/ from CHANGELOG.md")
    parser.add_argument("docs", nargs="?", default=str(ROOT / "docs"))
    parser.add_argument("--check", action="store_true", help="fail when committed pages are stale")
    parser.add_argument("--changelog", default=str(CHANGELOG))
    args = parser.parse_args()

    changelog = Path(args.changelog)
    if not changelog.is_file():
        print(f"changelog not found: {changelog}", file=sys.stderr)
        return 2

    releases = published(parse_changelog(changelog.read_text(encoding="utf-8")))
    if not releases:
        print("no released versions found in CHANGELOG.md", file=sys.stderr)
        return 2

    versions = [r["version"] for r in releases]
    if len(set(versions)) != len(versions):
        print(f"duplicate version sections in CHANGELOG.md: {versions}", file=sys.stderr)
        return 2

    pages = expected_pages(releases)
    target = Path(args.docs) / "releases"

    if args.check:
        problems = diff_pages(target, pages)
        if problems:
            print("release notes are stale: run scripts/build-releases-page.sh docs", file=sys.stderr)
            for problem in problems:
                print(f"  {problem}", file=sys.stderr)
            return 1
        print(
            f"release notes are current ({len(releases)} versions: "
            f"{', '.join(versions[:3])}{' …' if len(versions) > 3 else ''})"
        )
        return 0

    with tempfile.TemporaryDirectory() as staging:
        staging_path = Path(staging) / "releases"
        write_pages(staging_path, pages)
        # Only replace the published tree once a full render succeeded, so a crash
        # cannot leave docs/releases/ half-written for the site job to publish.
        write_pages(target, pages)
    print(f"wrote {len(releases)} release pages + index to {target} (newest: {versions[0]})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
