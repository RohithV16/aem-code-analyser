package io.github.rohithv16.aem.analyser.cli;

import picocli.CommandLine.Model.CommandSpec;
import picocli.CommandLine.Model.OptionSpec;
import picocli.CommandLine.Model.PositionalParamSpec;

import java.util.ArrayList;
import java.util.List;
import java.util.Locale;

/**
 * Generates zsh and fish completion scripts from the command model.
 *
 * <p>picocli 4.7 ships a bash generator only, so zsh and fish are rendered here from the same
 * {@link CommandSpec} the parser uses. Because the option names, aliases and value candidates come
 * from the model, a new flag is completable the moment it is declared — there is no second list to
 * keep in sync.</p>
 */
final class ShellCompletion {

    private ShellCompletion() {
    }

    /** A native zsh {@code _arguments} script, including the static value candidates. */
    static String zsh(CommandSpec spec) {
        String name = spec.name();
        String function = "_" + name.replace('-', '_');
        List<String> lines = new ArrayList<>();
        for (OptionSpec option : spec.options()) {
            lines.add("    " + zshOption(option));
        }
        for (PositionalParamSpec positional : spec.positionalParameters()) {
            lines.add("    '::" + labelOf(positional.paramLabel()) + ":_files -/'");
        }
        StringBuilder script = new StringBuilder();
        script.append("#compdef ").append(name).append('\n');
        script.append("# Generated by ").append(name).append(" --generate-completion zsh\n\n");
        script.append(function).append("() {\n");
        script.append("  _arguments -s \\\n");
        for (int i = 0; i < lines.size(); i++) {
            script.append(lines.get(i));
            // The last entry must not end in a continuation, or the shell waits for more input.
            script.append(i < lines.size() - 1 ? " \\\n" : "\n");
        }
        script.append("}\n\n");
        script.append("compdef ").append(function).append(' ').append(name).append('\n');
        return script.toString();
    }

    /**
     * One {@code _arguments} entry. The brace group that carries several names sits <em>outside</em>
     * the quotes: zsh only expands {@code {-p,--project-root}} when it is unquoted, and a quoted
     * brace group is a literal that never matches.
     */
    private static String zshOption(OptionSpec option) {
        List<String> names = List.of(option.names());
        StringBuilder line = new StringBuilder();
        if (names.size() > 1) {
            line.append('{').append(String.join(",", names)).append('}');
            line.append('\'');
        } else {
            line.append('\'');
            if (!names.isEmpty()) {
                line.append(names.get(0));
            }
        }
        line.append('[').append(sanitise(description(option))).append(']');
        if (takesValue(option)) {
            line.append(':').append(labelOf(option.paramLabel()));
            List<String> candidates = candidates(option);
            if (!candidates.isEmpty()) {
                line.append(":(").append(String.join(" ", candidates)).append(')');
            }
        }
        line.append('\'');
        return line.toString();
    }

    /** A fish script; {@code -a} carries the value candidates for {@code --fail-on}/{@code --format}. */
    static String fish(CommandSpec spec) {
        String name = spec.name();
        StringBuilder script = new StringBuilder();
        script.append("# Generated by ").append(name).append(" --generate-completion fish\n\n");
        for (OptionSpec option : spec.options()) {
            List<String> longs = new ArrayList<>();
            List<String> shorts = new ArrayList<>();
            for (String optionName : option.names()) {
                if (optionName.startsWith("--")) {
                    longs.add(optionName.substring(2));
                } else if (optionName.length() == 2 && optionName.startsWith("-")) {
                    shorts.add(optionName.substring(1));
                }
            }
            // fish's `complete` takes one alias per invocation, so a two-name option emits one line
            // per long name and repeats the short alias, instead of stacking -l flags.
            List<String> longsOrOnce = longs.isEmpty() ? List.of("") : longs;
            for (String longName : longsOrOnce) {
                StringBuilder line = new StringBuilder("complete -c ").append(name);
                for (String shortName : shorts) {
                    line.append(" -s ").append(shortName);
                }
                if (!longName.isEmpty()) {
                    line.append(" -l ").append(longName);
                }
                line.append(" -d '").append(fishDescription(description(option))).append('\'');
                if (takesValue(option)) {
                    line.append(" -r");
                    List<String> candidates = candidates(option);
                    if (!candidates.isEmpty()) {
                        line.append(" -f -a '").append(String.join(" ", candidates)).append('\'');
                    }
                }
                script.append(line).append('\n');
            }
        }
        return script.toString();
    }

    private static boolean takesValue(OptionSpec option) {
        return option.arity().max > 0;
    }

    /** A parameter label without picocli's angle brackets, e.g. {@code <formats>} → {@code formats}. */
    private static String labelOf(String paramLabel) {
        if (paramLabel == null || paramLabel.isBlank()) {
            return "ARG";
        }
        String label = paramLabel.replace("<", "").replace(">", "").strip();
        return label.isEmpty() ? "ARG" : label;
    }

    /** The description as one line, safe inside a zsh {@code _arguments} bracket. */
    private static String sanitise(String description) {
        return description.replaceAll("[\\[\\]'\\\\:]", "").replaceAll("\\s+", " ").strip();
    }

    /** The description as one line, safe inside fish single quotes. */
    private static String fishDescription(String description) {
        return description.replace("'", "").replace("\n", " ").replaceAll("\\s+", " ").strip();
    }

    private static String description(OptionSpec option) {
        String[] lines = option.description();
        return lines == null || lines.length == 0 ? "" : String.join(" ", lines);
    }

    /**
     * Static value candidates from the annotation, upper-cased because both consumers are enums.
     * A split option (e.g. {@code --format}) is offered whole; the shell completes the value the
     * user is typing, which is what a comma list needs.
     */
    private static List<String> candidates(OptionSpec option) {
        Iterable<String> declared = option.completionCandidates();
        if (declared == null) {
            return List.of();
        }
        List<String> values = new ArrayList<>();
        for (String value : declared) {
            values.add(value.toUpperCase(Locale.ROOT));
        }
        return values;
    }
}
